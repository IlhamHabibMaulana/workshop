-- 1. Buat Tabel tasks
CREATE TABLE IF NOT EXISTS public.tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    judul VARCHAR(150) NOT NULL,
    deskripsi TEXT NULL,
    deadline DATE NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Pending',
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),

    -- Constraint Validasi TC-02: Judul tidak boleh berupa string kosong atau hanya spasi
    CONSTRAINT tasks_judul_not_empty CHECK (char_length(trim(both from judul)) > 0),

    -- Constraint Validasi Status: Hanya boleh 'Pending' atau 'Completed'
    CONSTRAINT tasks_status_valid CHECK (status IN ('Pending', 'Completed'))
);

-- Berikan komentar dokumentasi pada tabel dan kolom
COMMENT ON TABLE public.tasks IS 'Tabel utama penyimpan daftar tugas pengguna aplikasi To-Do List';
COMMENT ON COLUMN public.tasks.id IS 'Primary key unik tugas';
COMMENT ON COLUMN public.tasks.judul IS 'Judul tugas (wajib diisi, maks 150 karakter)';
COMMENT ON COLUMN public.tasks.deskripsi IS 'Catatan atau rincian instruksi tugas';
COMMENT ON COLUMN public.tasks.deadline IS 'Tanggal batas penyelesaian tugas';
COMMENT ON COLUMN public.tasks.status IS 'Status tugas: Pending atau Completed';

-- 2. Aktifkan Row Level Security (RLS)
ALTER TABLE public.tasks ENABLE ROW LEVEL SECURITY;

-- 3. Hapus Policy Lama (Jika Ada) untuk Mencegah Duplikasi
DROP POLICY IF EXISTS "Allow anon public read access on tasks" ON public.tasks;
DROP POLICY IF EXISTS "Allow anon public insert access on tasks" ON public.tasks;
DROP POLICY IF EXISTS "Allow anon public update access on tasks" ON public.tasks;
DROP POLICY IF EXISTS "Allow anon public delete access on tasks" ON public.tasks;

-- 4. Buat Kebijakan RLS untuk Role 'anon' (Workshop Demo Mode) dengan Validasi Ketat
-- A. Policy SELECT: Mengizinkan pembacaan seluruh daftar tugas
CREATE POLICY "Allow anon public read access on tasks"
ON public.tasks
FOR SELECT
TO anon
USING (true);

-- B. Policy INSERT: Mengizinkan penambahan data baru dengan validasi judul & status
CREATE POLICY "Allow anon public insert access on tasks"
ON public.tasks
FOR INSERT
TO anon
WITH CHECK (
    char_length(trim(both from judul)) > 0 
    AND status IN ('Pending', 'Completed')
);

-- C. Policy UPDATE: Mengizinkan pembaruan data & toggle status dengan validasi
CREATE POLICY "Allow anon public update access on tasks"
ON public.tasks
FOR UPDATE
TO anon
USING (true)
WITH CHECK (
    char_length(trim(both from judul)) > 0 
    AND status IN ('Pending', 'Completed')
);

-- D. Policy DELETE: Mengizinkan penghapusan baris data tugas
CREATE POLICY "Allow anon public delete access on tasks"
ON public.tasks
FOR DELETE
TO anon
USING (true);

